export const ACCOUNT_TRANSLATIONS = deepFreeze(
  Object.fromEntries(
    ACCOUNT_LOCALES.map((accountLocale) => [
      accountLocale,
      { ...BASE_ACCOUNT_TRANSLATIONS[accountLocale], ...ACCOUNT_UI_TRANSLATIONS[accountLocale] },
    ])
  )
);

export const ACCOUNT_I18N_PACKS = ACCOUNT_TRANSLATIONS;

export function normalizeAccountLocale(locale) {
  const requested = String(locale || '')
    .trim()
    .toLowerCase()
    .replaceAll('_', '-');
  if (requested === 'ko' || requested.startsWith('ko-')) return 'kr';
  const normalized = requested.split('-')[0];
  return ACCOUNT_LOCALES.includes(normalized) ? normalized : 'en';
}

export function createAccountTranslator(locale = 'en') {
  const normalized = normalizeAccountLocale(locale);
  const pack = ACCOUNT_TRANSLATIONS[normalized];
  const accountTr = (key, replacements = {}) =>
    (pack[key] ?? ACCOUNT_TRANSLATIONS.en[key] ?? key).replace(/\{(\w+)\}/g, (match, name) =>
      Object.hasOwn(replacements, name) ? String(replacements[name]) : match
    );
  accountTr.locale = normalized;
  return accountTr;
}

export function resolveAccountLocale(storage, navigatorRef = globalThis.navigator) {
  let storedLocale = '';
  try {
    storedLocale = storage?.getItem(ACCOUNT_LANGUAGE_STORAGE_KEY) || '';
  } catch {
    // Storage can be unavailable in privacy-restricted browsing contexts.
  }
  return normalizeAccountLocale(storedLocale || navigatorRef?.language || 'en');
}

export function applyAccountDocumentPreferences(documentRef, locale) {
  const normalized = normalizeAccountLocale(locale);
  documentRef.documentElement.lang = normalized === 'kr' ? 'ko' : normalized;
  documentRef.documentElement.dir = normalized === 'ar' ? 'rtl' : 'ltr';
  return normalized;
}

