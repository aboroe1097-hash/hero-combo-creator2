function freezeCatalogEntry(raw) {
  const [
    treeIndex,
    nodeSuffix,
    nodeName,
    effectLabel,
    statCode,
    troopCode,
    rowCode,
    maxLevel,
    curve,
    explicit,
    sign = 1,
    effectIndex = 0,
  ] = raw;
  const [techId, season, techName] = TREE_METADATA[treeIndex];
  const nodeId = 'node_' + nodeSuffix;
  const levelValues = Array.isArray(curve) ? Object.freeze([...curve]) : null;
  const valueModel = levelValues ? 'levelValues' : 'perLevel';
  return Object.freeze({
    progressKey: techId + ':' + nodeId,
    techId,
    nodeId,
    effectIndex,
    label: techName + ': ' + nodeName,
    effectLabel,
    statKey: STAT_KEYS[statCode],
    unit: statCode === 'cs' ? 'raw' : 'percent',
    appliesTo: Object.freeze({
      troopTypes: TROOP_TYPES[troopCode],
      rowIds: ROWS[rowCode],
      battleModes: Object.freeze(['pvp-field']),
    }),
    maxLevel,
    valueModel,
    levelValues,
    perLevel: levelValues ? null : curve,
    amountMultiplier: sign,
    verification: explicit ? 'exact-level-table' : 'canonical-text',
    provenance: Object.freeze({
      techId,
      nodeId,
      effectIndex,
      season,
      techName,
      nodeName,
      maxLevel,
      valueModel,
    }),
  });
}

