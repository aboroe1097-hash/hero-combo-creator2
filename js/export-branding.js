import { SITE_NAME, SITE_LOGO, SITE_URL } from './seo.js';
import { APP_VERSION } from './state.js';

export const EXPORT_SOURCE_CREDITS = Object.freeze([
  'DonPablone',
  'FedeSack',
  'Mtness',
  'Raven',
  'Cris Minime',
  'riseofcastles.net community',
  'Rustablesafe (concepts)',
]);

export const FORBIDDEN_WATERMARK_TOKENS = Object.freeze(['DONPABLONE']);

function composeDisplayName(siteName) {
  return `${siteName} — VTS 1097`;
}

export function getExportBranding(datasetMeta = {}) {
  const revision = datasetMeta.revision ? String(datasetMeta.revision) : '';
  const verificationStatus = datasetMeta.verificationStatus
    ? String(datasetMeta.verificationStatus)
    : '';
  return Object.freeze({
    siteName: SITE_NAME,
    siteUrl: SITE_URL,
    logoUrl: SITE_LOGO,
    displayName: composeDisplayName(SITE_NAME),
    appVersion: APP_VERSION,
    generatedAt: new Date().toISOString(),
    datasetRevision: revision,
    verificationStatus,
    sourceCredits: EXPORT_SOURCE_CREDITS,
  });
}

export function csvFooterLines(branding) {
  const brand = branding || getExportBranding();
  const lines = [
    `Generated by ${brand.displayName} v${brand.appVersion} — ${brand.siteUrl}`,
    `Generated at ${brand.generatedAt}`,
  ];
  if (brand.datasetRevision) {
    lines.push(`Data revision ${brand.datasetRevision}${brand.verificationStatus ? ` (${brand.verificationStatus})` : ''}`);
  }
  lines.push(`Sources: ${brand.sourceCredits.join(', ')}`);
  return Object.freeze(lines);
}

export function jsonMetaBlock(branding, schema, schemaVersion) {
  const brand = branding || getExportBranding();
  return Object.freeze({
    schema,
    schemaVersion,
    generatedAt: brand.generatedAt,
    app: Object.freeze({
      name: brand.siteName,
      displayName: brand.displayName,
      version: brand.appVersion,
      url: brand.siteUrl,
    }),
    dataset: Object.freeze({
      revision: brand.datasetRevision,
      verificationStatus: brand.verificationStatus,
    }),
    sources: brand.sourceCredits,
  });
}

export function truncateCanvasText(ctx, text, maxWidth) {
  let label = String(text || '');
  if (ctx.measureText(label).width <= maxWidth) return Object.freeze({ text: label, fits: true });
  while (label.length > 3 && ctx.measureText(`${label}…`).width > maxWidth) {
    label = label.slice(0, -1);
  }
  return Object.freeze({ text: `${label}…`, fits: false });
}

export function drawCanvasFooter(ctx, branding, options = {}) {
  if (!ctx || typeof ctx.fillText !== 'function') return false;
  const brand = branding || getExportBranding();
  const width = Number(options.width) > 0 ? options.width : 820;
  const x = Number(options.x) >= 0 ? options.x : 28;
  const y = Number(options.y) > 0 ? options.y : 100;
  const muted = options.mutedColor || 'rgba(100,116,139,0.75)';
  const accent = options.accentColor || '#60a5fa';

  const logo = options.logoImg;
  if (logo) {
    const size = options.logoSize || 16;
    ctx.save();
    ctx.beginPath();
    ctx.arc(x + size / 2, y - size / 3, size / 2, 0, Math.PI * 2);
    ctx.closePath();
    ctx.clip();
    ctx.drawImage(logo, x, y - size / 3 - size / 2, size, size);
    ctx.restore();
  }
  const textX = x + (logo ? (options.logoSize || 16) + 8 : 0);
  const maxWidth = Math.max(0, x + width - textX);

  ctx.save();
  ctx.font = options.fontLine1 || '600 11px Inter, system-ui, sans-serif';
  ctx.fillStyle = accent;
  ctx.textAlign = 'left';
  const line1 = truncateCanvasText(ctx, `${brand.displayName} v${brand.appVersion}`, maxWidth);
  ctx.fillText(line1.text, textX, y);

  ctx.font = options.fontLine2 || '500 10px Inter, system-ui, sans-serif';
  ctx.fillStyle = muted;
  const baseLine2 = brand.datasetRevision
    ? `Data ${brand.datasetRevision}${brand.verificationStatus ? ` · ${brand.verificationStatus}` : ''} · ${brand.generatedAt.slice(0, 10)}`
    : `${brand.generatedAt.slice(0, 10)}`;
  const sources = `Sources: ${brand.sourceCredits.join(', ')} · ${brand.siteUrl}`;
  let composed = `${baseLine2} · ${sources}`;
  let line2 = truncateCanvasText(ctx, composed, maxWidth);
  if (!line2.fits && brand.sourceCredits.length) {
    composed = `${baseLine2} · Sources: ${brand.sourceCredits[0]} · ${brand.siteUrl}`;
    line2 = truncateCanvasText(ctx, composed, maxWidth);
  }
  ctx.fillText(line2.text, textX, y + 14);
  ctx.restore();
  return line1.fits && line2.fits;
}

export function assertNoForbiddenWatermarks(text) {
  const haystack = String(text || '').toUpperCase();
  const hit = FORBIDDEN_WATERMARK_TOKENS.find((token) => haystack.includes(token));
  if (hit) throw new Error(`Export must not contain the third-party watermark token "${hit}".`);
  return true;
}
