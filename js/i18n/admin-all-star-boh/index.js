const packs = new Map([['en', ADMIN_ALL_STAR_BOH_EN]]);
const inFlight = new Map();

export const ADMIN_ALL_STAR_BOH_LOCALES = Object.freeze(['en', ...Object.keys(LOCALE_LOADERS)]);

export function resolveAdminAllStarBohLocale(locale) {
  const normalized = resolveRuntimeLocale(locale);
  return ADMIN_ALL_STAR_BOH_LOCALES.includes(normalized) ? normalized : 'en';
}

function normalizePack(module) {
  const candidate =
    module?.default ?? module?.ADMIN_ALL_STAR_BOH_TRANSLATIONS ?? module?.translations;
  if (!candidate || typeof candidate !== 'object' || Array.isArray(candidate)) return null;
  return Object.freeze(
    Object.fromEntries(
      Object.keys(ADMIN_ALL_STAR_BOH_EN).map((key) => [
        key,
        typeof candidate[key] === 'string' && candidate[key].trim()
          ? candidate[key]
          : ADMIN_ALL_STAR_BOH_EN[key],
      ])
    )
  );
}

function format(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (placeholder, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : placeholder
  );
}

export async function loadAdminAllStarBohLocale(locale) {
  const normalized = resolveAdminAllStarBohLocale(locale);
  if (packs.has(normalized)) return packs.get(normalized);

  if (!inFlight.has(normalized)) {
    inFlight.set(
      normalized,
      LOCALE_LOADERS[normalized]()
        .then((module) => {
          const pack = normalizePack(module);
          if (!pack) throw new TypeError(`Invalid Admin All-Star BoH locale pack: ${normalized}`);
          packs.set(normalized, pack);
          return pack;
        })
        .catch((error) => {
          console.warn(
            `[admin-all-star-boh-i18n] Failed to load ${normalized}; using canonical English.`,
            error
          );
          return ADMIN_ALL_STAR_BOH_EN;
        })
        .finally(() => inFlight.delete(normalized))
    );
  }

  return inFlight.get(normalized);
}

export function adminAllStarBohText(key, vars = {}, locale) {
  const normalized = resolveAdminAllStarBohLocale(locale);
  const pack = packs.get(normalized);
  return format(pack?.[key] ?? ADMIN_ALL_STAR_BOH_EN[key] ?? key, vars);
}
