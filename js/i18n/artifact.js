export const ARTIFACT_LOCALES = Object.freeze(Object.keys(PACKS));
export const ARTIFACT_KEYS = Object.freeze(Object.keys(EN));

export function resolveArtifactLocale(locale) {
  const normalized = resolveRuntimeLocale(locale);
  return Object.hasOwn(PACKS, normalized) ? normalized : 'en';
}

export function artifactText(key, values = {}, locale = 'en') {
  const pack = PACKS[resolveArtifactLocale(locale)] || EN;
  return String(pack[key] ?? EN[key] ?? key).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match
  );
}

export function auditArtifactPack(locale) {
  const pack = PACKS[resolveArtifactLocale(locale)] || {};
  return Object.freeze({
    missing: Object.freeze(ARTIFACT_KEYS.filter((key) => !String(pack[key] ?? '').trim())),
    extra: Object.freeze(Object.keys(pack).filter((key) => !Object.hasOwn(EN, key))),
  });
}
