function normalizeLocale(locale) {
  const primary = String(locale || 'en')
    .toLowerCase()
    .split('-')[0];
  const normalized = primary === 'ko' ? 'kr' : primary;
  return Object.hasOwn(COPY, normalized) ? normalized : 'en';
}

export function getEdenX1ShellCopy(locale) {
  return COPY[normalizeLocale(locale)] || COPY.en;
}

export function localizeEdenX1Shell(documentRef, locale) {
  if (!documentRef) return normalizeLocale(locale);
  const normalized = normalizeLocale(locale);
  const copy = getEdenX1ShellCopy(normalized);
  documentRef.title = copy.documentTitle;

  const description = documentRef.querySelector?.('meta[name="description"]');
  description?.setAttribute('content', copy.metaDescription);

  documentRef.querySelectorAll?.('[data-eden-x1-shell-aria]').forEach((element) => {
    const key = element.getAttribute('data-eden-x1-shell-aria');
    if (copy[key]) element.setAttribute('aria-label', copy[key]);
  });
  documentRef.querySelectorAll?.('[data-eden-x1-shell-title]').forEach((element) => {
    const key = element.getAttribute('data-eden-x1-shell-title');
    if (copy[key]) element.setAttribute('title', copy[key]);
  });
  return normalized;
}

