export function auditHeroAtlasUi() {
  const errors = [];
  const placeholderSignature = (value) =>
    [...String(value || '').matchAll(/\{([a-zA-Z0-9_]+)\}/g)]
      .map((match) => match[1])
      .sort()
      .join('|');
  for (const [locale, values] of Object.entries(ROWS)) {
    if (values.length !== KEYS.length)
      errors.push(`${locale}: expected ${KEYS.length}, got ${values.length}`);
    values.forEach((value, index) => {
      if (!String(value || '').trim()) errors.push(`${locale}.${KEYS[index] || index}: empty`);
      if (/[?�]|tokens truncated/iu.test(String(value || '')))
        errors.push(`${locale}.${KEYS[index] || index}: invalid text`);
      if (placeholderSignature(value) !== placeholderSignature(ROWS.en[index]))
        errors.push(`${locale}.${KEYS[index] || index}: placeholder mismatch`);
    });
    for (const key of ['season', 'state', 'skins']) {
      const value = String(EXTRA_UI[locale]?.[key] || '');
      if (!value.trim()) errors.push(`${locale}.${key}: empty`);
      if (/[?�]|tokens truncated/iu.test(value)) errors.push(`${locale}.${key}: invalid text`);
    }
  }
  return Object.freeze({ complete: errors.length === 0, errors: Object.freeze(errors) });
}

