function normalizeLocale(locale) {
  const primary = String(locale || 'en')
    .toLowerCase()
    .split('-')[0];
  if (primary === 'ko') return 'kr';
  return Object.hasOwn(COPY, primary) ? primary : 'en';
}

export function runtimeMiscT(locale, key, variables = {}) {
  const normalized = normalizeLocale(locale);
  const template = COPY[normalized]?.[key] || COPY.en[key] || key;
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function getRuntimeMiscCopy(locale = 'en') {
  return COPY[normalizeLocale(locale)] || COPY.en;
}

