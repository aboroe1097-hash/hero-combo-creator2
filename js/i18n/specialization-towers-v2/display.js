function interpolate(value, variables) {
  return String(value).replace(/\{(\w+)\}/g, (match, key) => variables[key] ?? match);
}

export function specializationDisplayText(locale, key, variables = {}) {
  const pack = DISPLAY_COPY[locale] || DISPLAY_COPY.en;
  return interpolate(pack[key] || DISPLAY_COPY.en[key] || key, variables);
}

export function localizeSpecializationResearchName(locale, name, troopName = '') {
  const source = String(name || '');
  const match = FAMILY_KEYS.find(([pattern]) => pattern.test(source));
  if (!match) return source;
  const suffix = source.match(/\b([IVX]+)$/u)?.[1] || '';
  const family = specializationDisplayText(locale, match[1]);
  return `${match[1] === 'researchTraining' && troopName ? `${troopName} ` : ''}${family}${suffix ? ` ${suffix}` : ''}`;
}

export function localizeSpecializationNodeName(locale, name) {
  return NODE_NAMES[locale]?.[name] || name;
}

export function localizeSpecializationEffect(locale, effect) {
  let localized = String(effect || '');
  const terms = EFFECT_TERMS[locale];
  if (!terms) return localized;
  for (const [source, target] of Object.entries(terms)) {
    localized = localized.replace(new RegExp(`\\b${source}\\b`, 'gu'), target);
  }
  return localized;
}
