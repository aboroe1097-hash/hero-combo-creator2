  function deepFreeze(value) {
    if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
    Object.values(value).forEach(deepFreeze);
    return Object.freeze(value);
  }

  function normalizeLocale(locale) {
    const candidate = String(locale || 'en')
      .toLowerCase()
      .split('-')[0];
    const mapped = candidate === 'ko' ? 'kr' : candidate;
    return SUPPORTED_LOCALES.includes(mapped) ? mapped : 'en';
  }

  function preferredLocale() {
    let candidate = '';
    try {
      candidate = global.localStorage?.getItem('vts_hero_lang') || '';
    } catch {
      /* use browser language */
    }
    return normalizeLocale(candidate || global.navigator?.language || 'en');
  }

  function getCopy(locale = preferredLocale()) {
    return COPY[normalizeLocale(locale)] || COPY.en;
  }

  function format(template, values = {}) {
    return String(template || '').replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => {
      return Object.hasOwn(values, key) ? String(values[key]) : match;
    });
  }

  function getPath(value, path) {
    return String(path || '')
      .split('.')
      .filter(Boolean)
      .reduce((current, key) => current?.[key], value);
  }

  function localizeStandalone(documentRef, page, locale = preferredLocale()) {
    if (!documentRef) return 'en';
    const normalized = normalizeLocale(locale);
    const copy = getCopy(normalized).standalone?.[page] || COPY.en.standalone?.[page];
    if (!copy) return normalized;
    documentRef.documentElement.lang = normalized === 'kr' ? 'ko' : normalized;
    documentRef.documentElement.dir = normalized === 'ar' ? 'rtl' : 'ltr';
    if (copy.documentTitle) documentRef.title = copy.documentTitle;
    documentRef.querySelectorAll('[data-vts-standalone-copy]').forEach((element) => {
      const value = getPath(copy, element.getAttribute('data-vts-standalone-copy'));
      if (typeof value === 'string') element.textContent = value;
    });
    return normalized;
  }

