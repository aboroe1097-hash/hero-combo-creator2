export const VELO_COPY_LOCALES = Object.freeze(Object.keys(COPY));

function normalizeLocale(locale) {
  const primary = String(locale || 'en')
    .toLowerCase()
    .split('-')[0];
  return primary === 'ko' ? 'kr' : primary;
}

/** The pack for exactly this locale, or an empty object (never English). */
export function getVeloCopy(locale) {
  return COPY[normalizeLocale(locale)] || Object.freeze({});
}

/** Locale first, then English from this pack; undefined when neither has it. */
export function veloCopyText(locale, key) {
  return getVeloCopy(locale)[key] ?? COPY.en[key];
}
